"""
17_feature_oc_table.py
======================
Complete per-feature operating-condition correlation table (all features),
replacing the aggregated heatmap with a transparent feature-by-feature listing.

For every candidate feature (both channels) reports the signed Spearman rho with
RPM and with temperature, both marginal (over all sweeps) and conditional
(partition-based: within-temp-block for RPM, within-RPM-step for temperature).

Reads 12_fullset_decomposition's cond_vs_marginal_full.csv.

Outputs (outputs/17_feature_oc_table/)
  feature_oc_table.tex     appendix-ready longtable (both channels)
  feature_oc_table.csv     tidy table with band/type columns
  table_ae.png, table_us.png   rendered tables for inspection

Usage
-----
    python scripts/17_feature_oc_table.py
"""

import sys

sys.stdout.reconfigure(encoding="utf-8")

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from ceramicspeed.config import load_config, get_output_dir

cfg = load_config()
OUTPUT_DIR = get_output_dir(cfg)
NEW_DIR = OUTPUT_DIR / "new"
CM_PATH = NEW_DIR / "correlations" / "tables" / "cond_vs_marginal_full.csv"
SCRIPT_DIR = NEW_DIR / "feature_oc_table"
SCRIPT_DIR.mkdir(parents=True, exist_ok=True)

_TYPE = {"rms": "amp", "peak": "amp", "std": "amp", "variance": "amp",
         "crest_factor": "shape", "shape_factor": "shape", "impulse_factor": "shape",
         "margin_factor": "shape", "skewness": "shape", "kurtosis": "shape",
         "mobility": "cplx", "complexity": "cplx"}
for _s in ("dominant_frequency", "center_frequency", "rms_frequency", "peak_frequency",
           "spectral_mean", "spectral_std", "spectral_skewness", "spectral_kurtosis",
           "spectral_flatness", "spectral_bandwidth", "frequency_weighted_std",
           "normalized_frequency_std", "frequency_skewness", "frequency_kurtosis",
           "normalized_bandwidth"):
    _TYPE[_s] = "spec"

_BAND_ORDER = {"broadband": 0, "20-500kHz": 1, "500-1000kHz": 2,
               "0-10kHz": 3, "10-20kHz": 4, "20-100kHz": 5}


def parse_feat(sensor, name):
    rest = name[len(sensor):] if name.startswith(sensor) else name
    left, _, stat = rest.partition("__")
    band = left[1:] if left.startswith("_") else "broadband"
    return (band or "broadband"), stat, _TYPE.get(stat, "other")


# %%
cm = pd.read_csv(CM_PATH)
parsed = [parse_feat(s, f) for s, f in zip(cm["sensor"], cm["feature"])]
cm["band"] = [p[0] for p in parsed]
cm["stat"] = [p[1] for p in parsed]
cm["type"] = [p[2] for p in parsed]
cm["_b"] = cm["band"].map(lambda b: _BAND_ORDER.get(b, 9))
cm = cm.sort_values(["sensor", "_b", "stat"]).reset_index(drop=True)

cols = ["sensor", "band", "stat", "type",
        "marg_rpm", "marg_temp", "cond_rpm", "cond_temp"]
tidy = cm[cols].copy()
tidy.to_csv(SCRIPT_DIR / "feature_oc_table.csv", index=False)
print(f"Wrote {len(tidy)} rows -> feature_oc_table.csv")


# %%
# ---- LaTeX longtable -------------------------------------------------------
def _fmt(v):
    return "--" if pd.isna(v) else f"{v:+.2f}"


lines = [
    r"% Auto-generated by 17_feature_oc_table.py",
    r"\begin{longtable}{llll rrrr}",
    r"\caption{Per-feature operating-condition coupling. Signed Spearman $\rho$ "
    r"with RPM and temperature, marginal (all sweeps) and conditional "
    r"(partition-based).}\label{tab:feature_oc}\\",
    r"\toprule",
    r"Ch. & Band & Feature & Type & $\rho_{\mathrm{RPM}}^{\mathrm{marg}}$ & "
    r"$\rho_{T}^{\mathrm{marg}}$ & $\rho_{\mathrm{RPM}}^{\mathrm{cond}}$ & "
    r"$\rho_{T}^{\mathrm{cond}}$ \\",
    r"\midrule \endfirsthead",
    r"\toprule Ch. & Band & Feature & Type & "
    r"$\rho_{\mathrm{RPM}}^{\mathrm{marg}}$ & $\rho_{T}^{\mathrm{marg}}$ & "
    r"$\rho_{\mathrm{RPM}}^{\mathrm{cond}}$ & $\rho_{T}^{\mathrm{cond}}$ \\ "
    r"\midrule \endhead",
    r"\bottomrule \endfoot",
]
for _, r in tidy.iterrows():
    stat = r["stat"].replace("_", r"\_")
    lines.append(
        f"{r['sensor']} & {r['band']} & {stat} & {r['type']} & "
        f"{_fmt(r['marg_rpm'])} & {_fmt(r['marg_temp'])} & "
        f"{_fmt(r['cond_rpm'])} & {_fmt(r['cond_temp'])} \\\\")
lines.append(r"\end{longtable}")
(SCRIPT_DIR / "feature_oc_table.tex").write_text("\n".join(lines), encoding="utf-8")
print("Wrote feature_oc_table.tex")


# %%
# ---- Rendered PNGs (one per channel) for inspection ------------------------
def _render(sensor, fname):
    s = tidy[tidy["sensor"] == sensor]
    cell = s[["band", "stat", "type", "marg_rpm", "marg_temp",
              "cond_rpm", "cond_temp"]].copy()
    for c in ["marg_rpm", "marg_temp", "cond_rpm", "cond_temp"]:
        cell[c] = cell[c].map(_fmt)
    fig, ax = plt.subplots(figsize=(11, 0.32 * len(s) + 1))
    ax.axis("off")
    head = ["band", "feature", "type", "ρ RPM\n(marg)", "ρ T\n(marg)",
            "ρ RPM\n(cond)", "ρ T\n(cond)"]
    t = ax.table(cellText=cell.values, colLabels=head, loc="center", cellLoc="center")
    t.auto_set_font_size(False); t.set_fontsize(7.5); t.scale(1, 1.25)
    for j in range(len(head)):
        t[(0, j)].set_facecolor("#1f4e79")
        t[(0, j)].set_text_props(color="white", weight="bold")
    # shade strong temperature coupling (|cond ρ_T| >= 0.3)
    for i, (_, row) in enumerate(s.iterrows(), start=1):
        if abs(row["cond_temp"]) >= 0.3:
            t[(i, 6)].set_facecolor("#ffe0b3")
        if abs(row["cond_rpm"]) >= 0.3:
            t[(i, 5)].set_facecolor("#cfe2f3")
    ax.set_title(f"{sensor} — per-feature operating-condition coupling "
                 f"(shaded |cond ρ| ≥ 0.3)", pad=10)
    fig.savefig(SCRIPT_DIR / fname, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"Saved: {fname}")


_render("AE", "table_ae.png")
_render("US", "table_us.png")


# %%
# ---- Signed per-feature heatmaps (diverging) -------------------------------
def _heatmap(sensor, fname):
    s = tidy[tidy["sensor"] == sensor].reset_index(drop=True)
    M = s[["marg_rpm", "marg_temp", "cond_rpm", "cond_temp"]].values.astype(float)
    labels = [f"{b} · {st}" for b, st in zip(s["band"], s["stat"])]
    fig, ax = plt.subplots(figsize=(6.6, 0.30 * len(s) + 1.4))
    im = ax.imshow(M, cmap="RdBu_r", vmin=-1, vmax=1, aspect="auto")
    ax.set_xticks(range(4))
    ax.set_xticklabels(["ρ RPM\n(marg)", "ρ T\n(marg)", "ρ RPM\n(cond)", "ρ T\n(cond)"])
    ax.set_yticks(range(len(s))); ax.set_yticklabels(labels, fontsize=6.5)
    for i in range(len(s)):
        for j in range(4):
            v = M[i, j]
            ax.text(j, i, "--" if np.isnan(v) else f"{v:+.2f}", ha="center", va="center",
                    fontsize=6, color="white" if abs(v) > 0.55 else "black")
    # horizontal separators where the sub-band changes
    bands = s["band"].values
    for i in range(1, len(s)):
        if bands[i] != bands[i - 1]:
            ax.axhline(i - 0.5, color="k", lw=1.0)
    ax.set_title(f"{sensor} — per-feature operating-condition coupling (signed ρ)")
    fig.colorbar(im, ax=ax, label="Spearman ρ", shrink=0.5)
    fig.tight_layout()
    fig.savefig(SCRIPT_DIR / fname, dpi=150, bbox_inches="tight")
    plt.close()
    print(f"Saved: {fname}")


_heatmap("AE", "heatmap_ae.png")
_heatmap("US", "heatmap_us.png")

print(f"\nAll outputs -> {SCRIPT_DIR}")

if __name__ == "__main__":
    print("\n17_feature_oc_table complete.")
